"""Generate Pi sections from saved evidence, never smoke efficacy.

No model/measurement, no change to raw. Full20 and the later two-image pilot
remain separate; all their failed quality decisions are mandatory assertions.
"""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
OUT=Path(__file__).resolve().parent
OLD='sponge-sim/results/pi3b_600mhz_20261114/'
NEW='sponge-sim/results/pi3b_swapguard_v2_20261114/'
FULL='sponge-sim/results/pi3b_full20_20261114/'


def load(name):
    return json.loads((ROOT/name).read_text(encoding='utf-8-sig'))


def render():
    old=load(OLD+'runs/full_01/summary.json')['pipeline_PI4']
    new=load(NEW+'runs/smoke_01/summary.json')['pipeline_PI4']
    audit=load(NEW+'closed_smoke_audit.json')
    status=load(NEW+'protocol_status.json')
    oldmap=load(OLD+'raw_source_map.json')
    if old['quality_pass'] or old['gates']['swap_off'] or new['quality_pass']:
        raise ValueError('Pi negative decisions changed; manual review required')
    if not new['gates']['swap_off'] or new['gates']['mde_ok'] or not new['audit']['structure_ok']:
        raise ValueError('unexpected pilot failure mechanism')
    if status['full_status']!='CANCELLED_NOT_STARTED':
        raise ValueError('unexpected full status')
    rawsha=lambda p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest()
    oldraw=OLD+'runs/full_01/pipeline_PI4/raw.jsonl'
    newraw=NEW+'runs/smoke_01/pipeline_PI4/raw.jsonl'
    assert rawsha(oldraw)==oldmap['raw_sha256']
    assert rawsha(newraw)==audit['raw_sha256']==new['audit']['raw_sha256']
    oldrows=[json.loads(x) for x in (ROOT/oldraw).read_text().splitlines()]
    trials=sum(r['kind']=='timing' for r in oldrows)
    header='% Generated by make_pi3b.py; numeric sources in pi3b_sources.json.\n'
    first=header+r'''\subsection{Physical Raspberry Pi: completed replay fails the swap gate}
\label{app:seg-pi3b-diagnostic}
'''+f'''A separately preregistered replay on a physical Raspberry Pi 3 Model B uses
YOLOv8n-seg, the same frozen clean/perturbed tensor pairs as the laptop replay,
and full-resolution masks. The board has a declared undervoltage condition
and operates at 600~MHz. The four-thread primary session completes all
{old['n_images']} images and {trials} timing trials. However, swap becomes active during
the session, violating the preregistered swap-off condition. The session is
retained as diagnostic evidence and supplies no quality-qualified attack-latency
estimate. Both pin-load checks and the A/A and MDE gates pass: the geometric
mean A/A ratio is approximately {old['aa_cleanA_over_cleanB']['geomean_ratio']:.4f}, and the image-based 80\\%-power MDE
on the log-ratio scale is approximately {old['mde_log_80pct']:.4f}. These do not override the
swap failure; no images are removed to rescue the session.
'''+r'''
The subsequent single-thread and component sessions both fail the swap-off
precondition before any timing trial. They are not retried under the registered
infrastructure exception. Full-cohort NMS/mask decomposition and mask-count dose
measurements are unavailable. Smoke measurements are not substituted for those
endpoints, and separate medians are not subtracted to reconstruct stage costs.
'''+f'''
Candidate and retained-mask counts match the laptop values on all {old['n_images']}
frozen pairs, whereas none of the {2*old['n_images']} clean/perturbed prediction tensors
matches byte for byte. The declared PyTorch/torchvision versions differ;
finite count agreement is not numerical equivalence or general transfer validation.
'''
    second=header+r'''\subsection{Swap-protected Pi pilot: full run cancelled for precision}
\label{app:seg-pi3b-swapguard}
'''+f'''A later prospective protocol adds reversible runtime swap-unit masks,
independent cleanup and condition guards outside every clocked call. Its
{new['n_images']}-image pilot completes {new['audit']['n_timings']} timing trials and
{new['audit']['n_guards']} pre/post guard records with no logged condition violations.
Swap, pinning and sampled clock checks pass; none of the
{new['gates']['n_reference']} reference points is flagged. The geometric mean A/A ratio
is approximately {new['aa_cleanA_over_cleanB']['geomean_ratio']:.4f}, but the 80\\%-power MDE on the
log-ratio scale is {new['mde_log_80pct']:.4f}, exceeding the registered 0.05 limit.
This is a precision failure on two image units, not a measured 14\\% runtime
variation or evidence that pinning is impossible. The full run and the
single-thread/component sessions are cancelled, without retry or relabelling
the pilot as accepted. No attack-latency ratio from this pilot is used here.
'''+r'''
Configuration restoration succeeds, including the zram setup unit, and SSH
remains available. Separate sleeping-payload checks cover normal completion,
main/child termination, a supervisor timeout and a disconnected SSH frontend;
they are engineering checks, not inference measurements or a power-loss test.
The planned component-specific A/A controls have not yet been measured on a
full cohort. Neither Pi protocol establishes a deadline failure, service
denial, physical-patch efficacy or performance at a different clock/device.
'''
    paths=[OLD+n for n in ['runs/full_01/summary.json','runs/full_01/pipeline_PI4/raw.jsonl','structural_audit.json','raw_source_map.json']]
    paths += [NEW+n for n in ['runs/smoke_01/summary.json','runs/smoke_01/pipeline_PI4/raw.jsonl','runs/smoke_01/pipeline_PI4/gates.json','runs/smoke_01/restore.json','protocol_status.json','closed_smoke_audit.json']]
    paths += ['sponge-sim/results/pi3b_swapguard_v2_qa_20261114/qa_c_verification.json']
    sources=dict(status='REJECTED_PI_EVIDENCE_ONLY_NO_SMOKE_ATTACK_EFFECT',sources={p:dict(sha256=rawsha(p)) for p in paths},
                 selectors=dict(old='pipeline_PI4.{n_images,quality_pass,gates.swap_off,aa_cleanA_over_cleanB,mde_log_80pct,parity_vs_laptop}',
                                new='pipeline_PI4.{n_images,quality_pass,audit,gates,aa_cleanA_over_cleanB,mde_log_80pct}'),
                 old_pin_lines=oldmap['pin_lines'],new_pin_lines=audit['pin_rows'],
                 old_attack_estimate_eligible=False,new_attack_estimate_eligible=False,
                 format=dict(aa_ratios='.4f',mde_log='.4f'))
    full=load(FULL+'runs/full_01/summary.json')
    checked=load(FULL+'independent_audit.json')
    transfer=load(FULL+'transfer_verification.json')
    p=full['pipeline_PI4'];stage=full['stages_PI4']
    assert p['quality_pass'] and p['campaign_restore_ok'] and p['audit']['structure_ok']
    assert not stage['quality_pass'] and not stage['stage_controls']['nms']['mde_ok']
    assert stage['stage_controls']['mask']['mde_ok'] and full['pipeline_PI1']['missing']
    assert checked['status']=='INDEPENDENT_RAW_SCHEDULE_ARITHMETIC_VERIFIED'
    assert transfer['n_files']==21 and not transfer['full02_exists']
    h1=p['h1_adv_over_clean'];h2=p['h2_advcap_over_adv']
    third=header+r'''\subsection{Post-pilot full cohort: accepted total time, rejected component precision}
\label{app:seg-pi3b-full20}
'''+f'''After inspecting the rejected pilot, an approved, separately preregistered
protocol runs the originally planned {p['n_images']}-image cohort once, without another
pilot or any relaxation of the full-cohort gates. It reuses the same frozen
perturbations and images; it is neither an independent cohort nor a replication
chosen before all Pi observations. Four-thread execution is pinned to the four
Cortex-A53 CPUs, with FP32 inference and native full-resolution masks. The
declared supply condition and powersave governor are retained; sampled clocks
are 600~MHz, with both current-plus-historical and historical-only undervoltage
flags. No conversion to performance at a different clock is made.

The primary pipeline completes {p['audit']['n_timings']} trials. Both load checks pass,
none of {p['gates']['n_reference']} reference points is flagged, and all logged condition guards
pass with swap disabled. Its geometric A/A ratio is
{p['aa_cleanA_over_cleanB']['geomean_ratio']:.4f} and the image-based 80\\%-power log-MDE is
{p['mde_log_80pct']:.5f}, below 0.05. Independent configuration restoration also
passes. The primary total-time ratios therefore qualify under this protocol:
attacked/clean is {h1['geomean_ratio']:.3f} [95\\% CI
{h1['ratio_ci95'][0]:.3f}, {h1['ratio_ci95'][1]:.3f}], and candidate-cap/attacked is
{h2['geomean_ratio']:.3f} [{h2['ratio_ci95'][0]:.3f}, {h2['ratio_ci95'][1]:.3f}].
Both two-sided exact sign-flip tests have raw $p={h1['p_sign_flip']:.8f}$ and
Holm-adjusted $p={p['holm_h1_h2'][0]:.8f}$ in the two-hypothesis primary family.
Intervals resample images 20,000 times; they do not cover perturbation-seed,
board or supply variation. The median per-image forward share is
{100*p['forward_share']['clean']:.1f}\\% for clean inputs and
{100*p['forward_share']['adv']:.1f}\\% for perturbed inputs; separate timing medians
are not subtracted to reconstruct components.

The following component session completes {stage['audit']['n_timings']} trials on all
{stage['n_images']} images, including the available mask-count doses on the first five.
However, its attacked-workload NMS A/A geometric ratio is
{stage['stage_controls']['nms']['geomean_ratio']:.4f}, with log-MDE
{stage['stage_controls']['nms']['mde_log_80pct']:.4f}: both NMS precision gates fail.
The corresponding mask control is {stage['stage_controls']['mask']['geomean_ratio']:.4f}, with log-MDE
{stage['stage_controls']['mask']['mde_log_80pct']:.4f}, passing its own gates. The registered
joint component gate nevertheless fails: all component and dose estimates
remain diagnostic, and the not-yet-started single-thread session is cancelled.
No image is dropped and no session is retried. Fixed torchvision dispatch does
not by itself ensure stable wrapper timing; this endpoint includes filtering,
preparation and the fixed kernel, rather than only the bare kernel.

All {p['n_images']} pairs match the laptop candidate and retained-mask counts, but
{p['parity_vs_laptop']['prediction_bytes_equal']} of {2*p['n_images']} clean/perturbed prediction tensors match byte for byte.
The PyTorch/torchvision versions differ. This accepted total-time replay does
not override either earlier rejected protocol, establish a service deadline
failure or denial of service, or validate a physical patch or another device.
'''
    fullpaths=[FULL+n for n in ('runs/full_01/summary.json','runs/full_01/pipeline_PI4/raw.jsonl',
        'runs/full_01/stages_PI4/raw.jsonl','runs/full_01/pipeline_PI4/gates.json','runs/full_01/stages_PI4/gates.json',
        'runs/full_01/restore.json','runs/full_01/campaign_terminal.json','independent_audit.json','raw_source_map.json','transfer_verification.json')]
    sources['sources'].update({path:dict(sha256=rawsha(path)) for path in fullpaths})
    sources.update(status='SEPARATE_PI_PROTOCOLS_PRIMARY_FULL20_ACCEPTED_COMPONENTS_REJECTED',
                   full_attack_estimate_eligible=True,full_component_estimate_eligible=False,
                   full_selectors='pipeline_PI4.{audit,gates,h1_adv_over_clean,h2_advcap_over_adv,holm_h1_h2,aa_cleanA_over_cleanB,mde_log_80pct,forward_share,parity_vs_laptop}; stages_PI4.{audit,stage_controls,quality_pass}; pipeline_PI1.missing',
                   full_raw_map=FULL+'raw_source_map.json',
                   full_format=dict(primary_ratios='.3f',aa='.4f',mde_primary='.5f',mde_stage='.4f',p='.8f',forward_percent='.1f'))
    return {'pi3b_diagnostic':first,'pi3b_swapguard_v2':second,'pi3b_full20':third},sources


def main():
    texts,sources=render()
    for name,text in texts.items():
        (OUT/(name+'.tex')).write_text(text,encoding='utf-8',newline='\n')
    (OUT/'pi3b_sources.json').write_text(json.dumps(sources,indent=2)+'\n',encoding='utf-8',newline='\n')


if __name__=='__main__':
    main()
