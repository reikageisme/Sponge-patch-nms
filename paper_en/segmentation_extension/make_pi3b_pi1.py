"""Generate the Pi 3B single-thread (idle-USB-SSD) subsection from saved evidence.

No model/measurement, no change to raw. This is a DECLARED SEPARATE condition from the
four-thread PI4 run (which had no USB); the two are never pooled. The qualified run must
pass every gate, including ssd_idle; otherwise this generator refuses.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
RUN = 'sponge-sim/results/pi3b_pi1_ssd_20261115/runs/full_01/'


def load(name):
    return json.loads((ROOT / name).read_text(encoding='utf-8-sig'))


s = load(RUN + 'summary.json')['pipeline_PI1']
g = s['gates']
need = ['completed', 'images_complete', 'governor_ok', 'clock_ok', 'swap_off', 'reference_ok',
        'pin_ok', 'aa_ok', 'mde_ok', 'ssd_idle']
if not s['quality_pass'] or not all(g.get(k) for k in need):
    raise ValueError('PI1-SSD run is not fully qualified; manual review required')
if g['usb_sectors_written_values'] != {'sda': [0], 'sdb': [0]}:
    raise ValueError('declared-idle SSD performed I/O; condition broken')
rawsha = hashlib.sha256((ROOT / (RUN + 'pipeline_PI1/raw.jsonl')).read_bytes()).hexdigest()

h1, h1lo, h1hi = s['h1_adv_over_clean']['geomean_ratio'], *s['h1_adv_over_clean']['ratio_ci95']
h2, h2lo, h2hi = s['h2_advcap_over_adv']['geomean_ratio'], *s['h2_advcap_over_adv']['ratio_ci95']
ms = s['median_ms_across_images']
fwd = s['forward_share']['clean']
n = s['n_images']


def f2(x):
    return f'{x:.2f}'


def f3(x):
    return f'{x:.3f}'


tex = (
    '% Generated by make_pi3b_pi1.py; numeric sources in pi3b_pi1_ssd_sources.json.\n'
    '\\subsection{Physical Raspberry Pi: single thread with an idle USB SSD attached}\n'
    '\\label{app:pi3b-pi1}\n'
    'A separately preregistered run (\\texttt{prereg-pi3b-pi1-ssd-20261115}) measures the same '
    'twenty frozen pairs and YOLOv8n-seg on a single pinned CPU core of the same board, at the '
    'same declared 600~MHz undervoltage. Unlike the four-thread run, a separately powered USB SSD '
    '(ADATA SP900, unmounted) is attached throughout; this is a \\emph{distinct declared condition} '
    'and is not pooled with the four-thread result. The run records the SSD block-I/O counters at '
    'every environment snapshot: the written-sector count stays at zero on both USB disks for the '
    'whole session, so the disk is verified idle during timing. The session passes every quality '
    f'gate, including this idle-disk gate, with swap held off, the clock locked at 600~MHz, zero '
    f'flagged references and an A/A noise floor corresponding to an MDE of {f3(s["mde_ratio_80pct"])}. '
    f'On the single core the attacked-to-clean total-latency ratio is {f3(h1)} '
    f'(95\\% CI [{f3(h1lo)}, {f3(h1hi)}]; all {n} images positive), larger than the four-thread '
    f'ratio because mask construction benefits from multiple threads while the attacked mask work '
    f'dominates on one core. A pre-NMS cap reduces the attacked total to a factor of {f3(h2)} '
    f'(95\\% CI [{f3(h2lo)}, {f3(h2hi)}]). Median total latency is '
    f'{f2(ms["clean_total"]/1000)}~s clean, {f2(ms["adv_total"]/1000)}~s attacked and '
    f'{f2(ms["advcap_total"]/1000)}~s capped; the forward pass is {fwd*100:.0f}\\% of the clean '
    'total. These single-core numbers describe one undervolted board with a declared idle USB '
    'device and do not transfer to a 1.2~GHz operating point, to a no-USB condition, or to denial '
    'of service.\n')

(OUT / 'pi3b_pi1_ssd.tex').write_text(tex, encoding='utf-8')
sources = dict(
    run=RUN, raw_sha256=rawsha, n_images=n,
    h1_adv_over_clean='summary.json:pipeline_PI1.h1_adv_over_clean.geomean_ratio/ratio_ci95',
    h2_advcap_over_adv='summary.json:pipeline_PI1.h2_advcap_over_adv.geomean_ratio/ratio_ci95',
    median_ms='summary.json:pipeline_PI1.median_ms_across_images',
    forward_share='summary.json:pipeline_PI1.forward_share.clean',
    ssd_idle='summary.json:pipeline_PI1.gates.usb_sectors_written_values',
    quality_pass=s['quality_pass'], values=dict(h1=h1, h1_ci=[h1lo, h1hi], h2=h2, h2_ci=[h2lo, h2hi],
                                                median_ms=ms, forward_share=fwd, mde_ratio=s['mde_ratio_80pct']))
(OUT / 'pi3b_pi1_ssd_sources.json').write_text(json.dumps(sources, indent=1) + '\n', encoding='utf-8')
print('wrote pi3b_pi1_ssd.tex; H1', f3(h1), 'H2', f3(h2), 'raw_sha', rawsha[:12])
