"""Render only the closed, quality-qualified USB-present memory experiment.

No model/device work. Preserve the USB-absent failure and rejected timing
controls; the fresh-process memory result cannot qualify their endpoints.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
BASE = 'sponge-sim/results/pi3b_renderer_memory_usb_20261115/'


def load(path):
    return json.loads((ROOT/path).read_text(encoding='utf-8'))


def render():
    summary_path = BASE+'runs/memory_full_01/summary.json'
    audit_path = BASE+'independent_full_audit.json'
    s, a = load(summary_path), load(audit_path)
    assert s['quality_pass'] and s['restore_ok'] and s['controller_terminal_ok']
    assert a['status'] == 'INDEPENDENT_FULL_RAW_REPLAY_PASS' and a['n_images'] == 20 and a['n_jobs'] == 360
    assert all(v['aa_ok'] and v['mde_ok'] for v in s['aa_controls'].values())
    # These earlier closed failures are mandatory evidence, not superseded runs.
    v1_path = 'sponge-sim/results/pi3b_renderer_memory_v1_20261114/runs/memory_smoke_01/summary.json'
    old = load(v1_path)
    assert not old['quality_pass'] and not old['session_gate_pass'] and old['audit']['n_jobs'] == 0
    old_timing = load('sponge-sim/results/pi3b_full20_20261114/runs/full_01/summary.json')
    assert old_timing['pipeline_PI4']['quality_pass'] and not old_timing['stages_PI4']['quality_pass']
    p = s['primary_adv_candidate_over_baseline']
    c = s['secondary_clean_candidate_over_baseline']
    aa = s['aa_controls']
    raw_path = BASE+'runs/memory_full_01/original/memory/raw.jsonl'
    assert hashlib.sha256((ROOT/raw_path).read_bytes()).hexdigest() == a['raw_sha256']
    text = r'''% Generated by make_pi3b_memory.py; exact numeric/raw mappings in pi3b_memory_sources.json.
\subsection{A separate Pi renderer memory intervention}
\label{app:seg-pi3b-memory}
A later protocol, registered before its first memory observation, compares
the frozen native renderer (32-million-pixel chunk budget) with a combined
preallocated uint8-output/direct-copy implementation using a 16-million-pixel
budget. Coefficient multiplication, resize, threshold and crop are retained.
The comparison reuses the same 20 previously observed clean/attacked input
pairs, with one attack initialization per image. It is not an independent
cohort or an additional attack-seed study. The physical Pi 3B remains
undervoltage-limited to 600~MHz with four threads. An intentionally attached
SSD is unmounted and idle; source/cache/log paths remain on the SD card.
This is a separately declared condition rather than a retry of the earlier
USB-absent memory smoke, which aborts at the USB guard before any RSS sample;
that failed smoke and its cancelled full run are retained.

Each fresh process imports the runtime, validates one frozen cache, performs
one same-renderer single-mask warmup, renders and hashes the output. No model
is resident in that process. Linux \texttt{ru\_maxrss} is read after the digest
and converted from KiB to bytes. The endpoint includes imports, validation,
warmup, observers, allocator/workspaces and output; it is neither incremental
nor isolated renderer peak memory. Startup high-water and 1-KiB counter
resolution may conceal small differences. The two native copies (A/B) and
candidate, each repeated three times for both clean/attacked cases, are
randomized within each image/repetition. The per-image denominator pools all
six native samples before taking the median; the numerator is the median of
three candidate samples. Images, not processes, are the inferential units.
'''+f'''
All {a['n_jobs']} fresh processes finish and all output digests match the
frozen cache digests. Both clean and attacked A/A controls meet the fixed
absolute mean-log-ratio limit 0.02 and MDE limit 0.05; their MDE values are
{aa['clean']['mde_log_80pct']:.8f} and {aa['adv']['mde_log_80pct']:.8f}, respectively.
Sampled clock, thermal, swap, affinity and USB-identity/I/O guards pass,
as do independent cleanup and restoration checks. These sampled guards do
not establish continuous extrema or formal equivalence.

For the single confirmatory attacked endpoint, the geometric mean
candidate/native whole-process high-water ratio is {p['geomean_ratio']:.6f}
(image-bootstrap 95\\% CI [{p['ratio_ci95'][0]:.6f}, {p['ratio_ci95'][1]:.6f}]),
approximately {100*(1-p['geomean_ratio']):.2f}\\% lower. The 20,000-resample bootstrap uses
RNG seed {p['bootstrap_seed']}; the exact two-sided sign-flip value is
$2/2^{{20}}={p['p_sign_flip']:.12f}$, its minimum resolution, with all image
units in the same direction. The paired log-ratio effect size is
$d_z={p['dz']:.4f}$. Clean-case results are descriptive: ratio
{c['geomean_ratio']:.6f}, CI [{c['ratio_ci95'][0]:.6f}, {c['ratio_ci95'][1]:.6f}].
'''+r'''

The combined change does not isolate the effects of chunk size and output
assembly. It establishes a memory reduction conditional on these caches
and this device/runtime; it supplies no integrated model-resident RSS,
renderer latency, throughput, energy, new accuracy estimate or deadline
failure. Finite digest agreement is not universal output equivalence.
The earlier rejected NMS component controls and cancelled single-thread
session remain unchanged. Reduced RSS alone does not identify the cause of
NMS variation or establish denial of service.
The SSH frontend disconnects during this run; the same owned systemd
invocation continues without relaunch. Only service-state waiting resumes,
and raw collection starts after authoritative termination. The transport
failure, original data and postterminal recovery receipt are retained under
\texttt{prereg-pi3b-renderer-memory-usb-20261115}.
'''
    paths = [summary_path, audit_path, raw_path, v1_path,
             'sponge-sim/results/pi3b_full20_20261114/runs/full_01/summary.json',
             'sponge-sim/studies/pi3b_renderer_memory_usb_20261115/memory_registration.json',
             'sponge-sim/studies/pi3b_renderer_memory_usb_20261115/cache_manifest.json',
             BASE+'full_transfer_verification.json', BASE+'full_transport_recovery_receipt.json',
             BASE+'runs/memory_full_01/manifest.json', BASE+'runs/memory_full_01/original/restore.json',
             'sponge-sim/prereg/PREREG_PI3B_RENDERER_MEMORY_USB_20261115.md']
    sources = {p: hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in paths}
    mapping = dict(tag=a['tag'], commit=a['commit'], quality_qualified_memory=True,
        timing_or_dos_claim=False, primary=summary_path+':primary_adv_candidate_over_baseline',
        secondary_descriptive=summary_path+':secondary_clean_candidate_over_baseline',
        aa=summary_path+':aa_controls', per_image=audit_path+':table[*].raw_lines',
        raw=raw_path+':1..360 result.ru_maxrss_bytes', sources=sources)
    return text, mapping


if __name__ == '__main__':
    text, mapping = render()
    (OUT/'pi3b_memory.tex').write_text(text, encoding='utf-8', newline='\n')
    (OUT/'pi3b_memory_sources.json').write_text(json.dumps(mapping, indent=2), encoding='utf-8', newline='\n')
